"""A second worked example of a task as a plugin (docs/TUTORIAL.md): questions with reference answers, nothing
compiled.

A pool is a directory holding `qa.jsonl`, one question per line: `{"id", "question", "answer", "aliases"?}`. The model
is asked the question and told to end its reply with a line `Answer: <answer>`. A reply without that line gets one
repair turn that says so (this module's parse and feedback); there is no compile step (`rollout.compile_adapter:
none`). The reward service runs one leg, `ref.answer`: the last `Answer:` line, normalised, against the reference and
its aliases. An optional judge (adapter setting `judge`: a command) is asked about an answer that does not match: it
reads `{"question", "reference", "answer"}` as JSON on stdin and prints `{"verdict": "correct"}` or `{"verdict":
"wrong"}`; anything else leaves the sample unscored. That is also the shape of a task whose reward is an external
tool's verdict.

Registered names: task `qa`; parse `qa.parse`; feedback `qa.feedback`; profile `qa-match` (qa-match.yaml); check
adapter `qa.match`; reward function `qa.v1`.

Two pools come with it: `gpu-facts/` (24 short questions on GPU programming, split train/held-out) and `arith/`
(3-digit multiplication, generated by make_arith.py, split train/held-out), the one the validation run trains on.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
SYSTEM = "You are a helpful assistant."
USER = "{question}\n\nEnd your reply with a line of the form 'Answer: <your answer>'."
ANSWER_RE = re.compile(r"^\s*\**\s*answer\s*\**\s*[:：]\s*(.+?)\s*$", re.IGNORECASE | re.MULTILINE)


def load_rows(pool_dir) -> list[dict]:
    rows = [json.loads(line) for line in (Path(pool_dir) / "qa.jsonl").read_text(encoding="utf-8").splitlines()
            if line.strip()]
    ids = [r["id"] for r in rows]
    if len(set(ids)) != len(ids):
        raise ValueError(f"{pool_dir}/qa.jsonl lists an id twice")
    return rows


def row_sha256(row: dict) -> str:
    return hashlib.sha256(json.dumps(row, sort_keys=True).encode("utf-8")).hexdigest()


def normalise(text: str) -> str:
    """Lower case, NFKC, outer quotes, backticks, a trailing full stop, commas between digits and runs of space
    removed: `**Answer:** "1,024."` and `answer: 1024` are one answer."""
    t = unicodedata.normalize("NFKC", text).strip().lower()
    t = t.strip("*`'\" ")
    t = re.sub(r"(?<=\d),(?=\d)", "", t)
    t = t.rstrip(".").strip()
    return re.sub(r"\s+", " ", t)


def final_answer(reply: str) -> str | None:
    """The last `Answer:` line's answer, or None."""
    found = ANSWER_RE.findall(reply)
    return found[-1] if found else None


def messages(row: dict) -> list[dict]:
    return [{"role": "system", "content": SYSTEM}, {"role": "user", "content": USER.format(question=row["question"])}]


def records(pool_dir, tokenizer, thinking):
    from aorlta.ids import sha256_ids
    from aorlta.rollout.templates import render_turn0
    from aorlta.schemas import PromptRecord, TaskRef

    out = []
    for row in load_rows(pool_dir):
        msgs = messages(row)
        out.append(PromptRecord(
            prompt_id=f"qa:{row['id']}", turn0_ids=None, messages=msgs,
            prompt_ids_sha256=sha256_ids(render_turn0(tokenizer, msgs, thinking)),
            task=TaskRef(contract_id=f"qa:{row['id']}", parent_id=None, parent_healthy=None, reference_kind=None,
                         task_sha256=row_sha256(row)),
            source="standin"))
    return out


class QaParse:
    """`qa.parse`: a reply with an `Answer:` line is an answer (nothing to compile); one without is rejected with a
    message, which `qa.feedback` turns into a repair turn."""

    name = "qa.parse"

    def check_prompts(self, prompts, thinking, max_repair_turns=0):
        return None

    def check(self, text, thinking, prompt):
        from aorlta.rollout.compile_check import ParseOutcome

        reply = text.rsplit("</think>", 1)[-1] if thinking == "on" else text
        answer = final_answer(reply)
        if answer is None:
            return ParseOutcome("rejected", rejection=(
                "Your reply has no final line of the form 'Answer: <your answer>'. Give your answer on such a line.",
                "no_answer"))
        return ParseOutcome("edits", code=answer)


class QaFeedback:
    name = "qa.feedback"

    def build(self, errors, max_chars):
        from aorlta.rollout.feedback import build_feedback

        return build_feedback(errors, max_chars)

    def build_apply(self, message, reason):
        from aorlta.rollout.feedback import Feedback

        return Feedback(message, 0, 0)


class QaMatch:
    """`qa.match`, leg `ref.answer`: clean when the final answer matches the reference or an alias after
    `normalise`, or the judge (settings `judge`, a command as a list) says it is correct; `fail` `wrong_answer`, or
    `no_answer` when the reply has no `Answer:` line; unsettled when the task is unknown, the reply cannot be read,
    or the judge does not give a verdict."""

    legs = ("ref.answer",)
    resource = "local_cpu"

    def __init__(self, ctx):
        from aorlta.reward.adapters.base import ProcessRunner
        from aorlta.reward.adapters.toolchain import file_identity

        self.name, self.ctx = ctx.name, ctx
        self.judge = ctx.settings.get("judge")
        self.judge_timeout_s = float(ctx.settings.get("judge_timeout_s", 60.0))
        self.version = "1"  # cached legs are keyed by it: the judge, which can turn a mismatch clean, is part of it
        if self.judge:
            files = {a: file_identity(a) for a in self.judge if isinstance(a, str) and Path(a).is_file()}
            exe = shutil.which(self.judge[0]) if isinstance(self.judge[0], str) else None  # as PATH finds it, if bare
            if exe:
                files[f"exe:{self.judge[0]}"] = f"{os.path.realpath(exe)}:{file_identity(exe)}"
            ident = json.dumps({"judge": list(self.judge), "timeout_s": self.judge_timeout_s, "files": files},
                               sort_keys=True)
            self.version = f"1+judge-{hashlib.sha256(ident.encode()).hexdigest()[:16]}"
        self.runner = ProcessRunner()  # kills the judge's whole process group on a timeout or at close()
        self.rows = {}
        for pool in ctx.pools:
            if (Path(pool) / "qa.jsonl").is_file():
                for row in load_rows(pool):
                    self.rows[row_sha256(row)] = row

    def run(self, job):
        from aorlta.reward.adapters.base import make_result, unsettled

        t0 = self.ctx.clock()
        try:
            row = self.rows.get(job.task_sha256)
            response = job.inputs.get("response")
            if job.leg != "ref.answer" or row is None or not response:
                return unsettled(job, "adapter_error", t_start=t0, t_end=self.ctx.clock())
            answer = final_answer(Path(response).read_text(encoding="utf-8").rsplit("</think>", 1)[-1])
            if answer is None:
                return make_result(job, "fail", "no_answer", t_start=t0, t_end=self.ctx.clock())
            wanted = {normalise(a) for a in [row["answer"], *row.get("aliases", [])]}
            if normalise(answer) in wanted:
                return make_result(job, "clean", t_start=t0, t_end=self.ctx.clock())
            if not self.judge:
                return make_result(job, "fail", "wrong_answer", t_start=t0, t_end=self.ctx.clock())
            verdict = self._judge(row, answer)
            if verdict == "correct":
                return make_result(job, "clean", t_start=t0, t_end=self.ctx.clock())
            if verdict == "wrong":
                return make_result(job, "fail", "wrong_answer", t_start=t0, t_end=self.ctx.clock())
            return unsettled(job, "judge_no_verdict", t_start=t0, t_end=self.ctx.clock())
        except Exception:  # noqa: BLE001 - an adapter never raises
            return unsettled(job, "adapter_error", t_start=t0, t_end=self.ctx.clock())

    def _judge(self, row, answer) -> str | None:
        proc = self.runner.run(list(self.judge), input=json.dumps({"question": row["question"],
                                                                   "reference": row["answer"], "answer": answer}),
                               timeout_s=min(self.judge_timeout_s, self.ctx.timeout_s))
        if proc.timed_out or proc.killed or proc.launch_error or proc.returncode != 0 or not proc.stdout.strip():
            return None
        try:
            out = json.loads(proc.stdout.strip().splitlines()[-1])
        except ValueError:
            return None
        v = out.get("verdict") if isinstance(out, dict) else None
        return v if v in ("correct", "wrong") else None

    def controls(self):
        return []

    def health(self):
        return {"name": self.name, "responsive": True, "questions": len(self.rows)}

    def close(self):
        self.runner.close()


class QaV1:
    """`qa.v1`: +1.0 for a matching answer, -0.5 for a wrong one, -1.0 for no `Answer:` line; then -0.05 x the share
    of the token budget used. An unsettled leg leaves the sample unscored."""

    name = "qa.v1"
    version = "1"
    legs = ("ref.answer",)
    BASE = {"wrong_answer": -0.5, "no_answer": -1.0}

    def __init__(self, profile=None):
        from aorlta.reward.rewardfn.base import code_sha256

        self.settings = {}
        self.code_sha256 = code_sha256(__file__)

    def _base(self, legs):
        leg = legs.get("ref.answer")
        if leg is None:
            return "pending", "ref.answer"
        if leg.state == "clean":
            return "score", 1.0
        if leg.state == "fail" and leg.reason in self.BASE:
            return "score", self.BASE[leg.reason]
        return "unscored", f"ref.answer:{leg.reason or leg.state}"

    @staticmethod
    def _finish(base, cand):
        parts = {"base": float(base), "broke_healthy": 0.0,
                 "length": -0.05 * (cand.response_tokens / cand.max_new_tokens)}
        return parts["base"] + parts["broke_healthy"] + parts["length"], parts

    def compute(self, legs, cand):
        kind, value = self._base(legs)
        return (None, {"reason": str(value)}) if kind != "score" else self._finish(value, cand)

    def decide(self, partial, cand):
        from aorlta.reward.rewardfn.base import Decided, NeedMore, Unscored

        kind, value = self._base(partial)
        if kind == "pending":
            return NeedMore((value,))
        return Unscored(value) if kind == "unscored" else Decided(*self._finish(value, cand))

    @staticmethod
    def claims_clean(reward, parts):
        return reward is not None and isinstance(parts, dict) and parts.get("base", 0.0) > 0.0


def register() -> None:
    from aorlta import plugins

    plugins.register_task(plugins.Task("qa", records))
    plugins.register_parse_adapter("qa.parse", QaParse)
    plugins.register_feedback_template("qa.feedback", QaFeedback)
    plugins.register_profile("qa-match", HERE / "qa-match.yaml")
    plugins.register_check_adapter("qa.match", QaMatch)
    plugins.register_reward_fn("qa.v1", QaV1)


register()
